"""Hosted mode: a public deployment where nobody may bring their own code.

Uploaded code runs in a sandbox child, but a public server should not run strangers' code at all,
so every place code can enter calls `refuse_code` / `refuse_if_runs_code`. Library algorithms, the
lab, and block graphs without code blocks (their source is generated by us) keep working, and so
do the seeded marketplace listings (our own code).
"""

from app.config import get_settings

CODE = "disabled_in_hosted_mode"
MESSAGE = "Uploading or running your own code is turned off on this public server."


class HostedModeError(Exception):
    """Raised where code would enter; answered as 403 with `code` `disabled_in_hosted_mode`."""

    status_code = 403
    code = CODE

    def __init__(self, what: str = MESSAGE):
        super().__init__(what)
        self.message = what


def is_hosted() -> bool:
    return get_settings().hosted_mode


def refuse_code() -> None:
    """Call where uploaded or editor source arrives."""
    if is_hosted():
        raise HostedModeError()


def graph_runs_code(graph: dict | None) -> bool:
    """A block graph holds code when one of its custom blocks is a code block."""
    return bool(graph) and any(
        isinstance(e, dict) and e.get("kind") == "code" for e in (graph.get("custom_blocks") or [])
    )


def refuse_graph_code(graph: dict | None) -> None:
    if is_hosted() and graph_runs_code(graph):
        raise HostedModeError()


def refuse_saved_code(algo) -> None:
    """A saved algorithm (`UserAlgo`) runs someone's code when it holds editor source, or a block
    graph with a code block. A graph of built-in blocks compiles to source we generated: allowed."""
    if is_hosted() and algo.source is not None and (algo.graph is None or graph_runs_code(algo.graph)):
        raise HostedModeError()
